import type { ConversationItem } from "@/types";
import {
  normalizeItem,
  prepareThreadItems,
  upsertItem,
} from "@utils/threadItems";
import type { ThreadAction, ThreadState } from "../useThreadsReducer";
import {
  extractRenameText,
  looksAutoGeneratedThreadName,
  maybeRenameThreadFromAgent,
  mergeStreamingText,
  prefersUpdatedSort,
} from "./common";

export function reduceThreadItems(
  state: ThreadState,
  action: ThreadAction,
): ThreadState {
  switch (action.type) {
    case "addNotice": {
      const list = state.itemsByThread[action.threadId] ?? [];
      const notice: ConversationItem = {
        id: action.itemId,
        kind: "tool",
        toolType: "notice",
        title: `[${action.level}]`,
        detail: action.text,
        status: action.level === "error" ? "failed" : "completed",
      };
      return {
        ...state,
        itemsByThread: {
          ...state.itemsByThread,
          [action.threadId]: prepareThreadItems([...list, notice], {
            maxItemsPerThread: state.maxItemsPerThread,
          }),
        },
      };
    }
    case "addAssistantMessage": {
      const list = state.itemsByThread[action.threadId] ?? [];
      const message: ConversationItem = {
        id: `${Date.now()}-assistant`,
        kind: "message",
        role: "assistant",
        text: action.text,
      };
      return {
        ...state,
        itemsByThread: {
          ...state.itemsByThread,
          [action.threadId]: prepareThreadItems([...list, message], {
            maxItemsPerThread: state.maxItemsPerThread,
          }),
        },
      };
    }
    case "appendAgentDelta":
    case "completeAgentMessage": {
      const list = state.itemsByThread[action.threadId] ?? [];
      const index = list.findIndex((item) => item.id === action.itemId);
      const existing =
        index >= 0 && list[index].kind === "message" ? list[index] : undefined;
      const text =
        action.type === "appendAgentDelta"
          ? mergeStreamingText(existing?.text ?? "", action.delta)
          : action.text || existing?.text || "";
      if (existing?.text === text) return state;
      const updated = normalizeItem({
        ...existing,
        id: action.itemId,
        kind: "message",
        role: "assistant",
        text,
      });
      let updatedItems: ConversationItem[];
      if (existing) {
        updatedItems = [...list];
        updatedItems[index] = updated;
      } else {
        updatedItems = prepareThreadItems([...list, updated], {
          maxItemsPerThread: state.maxItemsPerThread,
        });
      }
      return {
        ...state,
        itemsByThread: {
          ...state.itemsByThread,
          [action.threadId]: updatedItems,
        },
        threadsByWorkspace: maybeRenameThreadFromAgent({
          workspaceId: action.workspaceId,
          threadId: action.threadId,
          items: updatedItems,
          itemId: action.itemId,
          hasCustomName: action.hasCustomName,
          threadsByWorkspace: state.threadsByWorkspace,
        }),
      };
    }
    case "upsertItem": {
      const list = state.itemsByThread[action.threadId] ?? [];
      const item = normalizeItem(action.item);
      const isUserMessage = item.kind === "message" && item.role === "user";
      const hadUserMessage = isUserMessage
        ? list.some(
            (entry) => entry.kind === "message" && entry.role === "user",
          )
        : false;
      const renameText = isUserMessage ? extractRenameText(item.text) : "";
      const updatedItems = prepareThreadItems(upsertItem(list, item), {
        maxItemsPerThread: state.maxItemsPerThread,
      });
      let nextThreadsByWorkspace = state.threadsByWorkspace;
      if (isUserMessage) {
        const threads = state.threadsByWorkspace[action.workspaceId] ?? [];
        const textValue = renameText;
        const updatedThreads = threads.map((thread) => {
          if (thread.id !== action.threadId) {
            return thread;
          }
          const looksAutoGenerated = looksAutoGeneratedThreadName(thread.name);
          const shouldRename =
            !hadUserMessage &&
            textValue.length > 0 &&
            looksAutoGenerated &&
            !action.hasCustomName;
          const nextName =
            shouldRename && textValue.length > 38
              ? `${textValue.slice(0, 38)}…`
              : shouldRename
                ? textValue
                : thread.name;
          return { ...thread, name: nextName };
        });
        const bumpedThreads =
          prefersUpdatedSort(state, action.workspaceId) && updatedThreads.length
            ? [
                ...updatedThreads.filter(
                  (thread) => thread.id === action.threadId,
                ),
                ...updatedThreads.filter(
                  (thread) => thread.id !== action.threadId,
                ),
              ]
            : updatedThreads;
        nextThreadsByWorkspace = {
          ...state.threadsByWorkspace,
          [action.workspaceId]: bumpedThreads,
        };
      }
      return {
        ...state,
        itemsByThread: {
          ...state.itemsByThread,
          [action.threadId]: updatedItems,
        },
        threadsByWorkspace: nextThreadsByWorkspace,
      };
    }
    case "setThreadItems":
      return {
        ...state,
        contextInheritanceByThread: {
          ...state.contextInheritanceByThread,
          [action.threadId]: action.contextInheritance ?? null,
        },
        itemsByThread: {
          ...state.itemsByThread,
          [action.threadId]: prepareThreadItems(action.items, {
            maxItemsPerThread: state.maxItemsPerThread,
          }),
        },
      };
    case "appendReasoningContent": {
      const list = state.itemsByThread[action.threadId] ?? [];
      const index = list.findIndex((item) => item.id === action.itemId);
      const existing =
        index >= 0 && list[index].kind === "reasoning"
          ? list[index]
          : undefined;
      const content = mergeStreamingText(existing?.content ?? "", action.delta);
      if (existing?.content === content) return state;
      const updated = normalizeItem({
        ...existing,
        id: action.itemId,
        kind: "reasoning",
        summary: existing?.summary ?? "",
        content,
      });
      const next = [...list];
      if (existing) next[index] = updated;
      else next.push(updated);
      return {
        ...state,
        itemsByThread: {
          ...state.itemsByThread,
          [action.threadId]: existing
            ? next
            : prepareThreadItems(next, {
                maxItemsPerThread: state.maxItemsPerThread,
              }),
        },
      };
    }
    default:
      return state;
  }
}
